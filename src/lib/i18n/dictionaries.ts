export const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  en,
  fr,
  ar,
};

export type TranslateParams = Record<string, string | number>;

export function translate(
  locale: Locale,
  key: MessageKey,
  params?: TranslateParams,
): string {
  // A stale or partially reloaded bundle must not crash a page because one
  // message is missing; fall back to the key itself.
  const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

/** Error codes returned by server actions, mapped to `error.*` messages. */
export function errorMessage(locale: Locale, code: string): string {
  const key = `error.${code}`;
  if (!(key in dictionaries.en)) return translate(locale, "error.unexpected");
  return translate(locale, key as MessageKey);
}

/** Server-action codes: `validation_*` map to `validation.*`, the rest to `error.*`. */
export function actionMessage(locale: Locale, code: string): string {
  if (code.startsWith("validation_")) {
    const key = `validation.${code.slice("validation_".length)}`;
    if (key in dictionaries.en) return translate(locale, key as MessageKey);
  }
  return errorMessage(locale, code);
}

/** Reasons passed in `?reason=` by the dashboard guard, mapped to `notice.*`. */
export function noticeMessage(locale: Locale, code: string): string {
  const key = `notice.${code}`;
  if (!(key in dictionaries.en)) return translate(locale, "notice.unexpected");
  return translate(locale, key as MessageKey);
}
